"""
inp_generator.py
Build CalculiX analysis deck (.inp) from mesh + BCs + loads.
"""
from __future__ import annotations

from pathlib import Path

from src.inp_mesh_utils import parse_inp_mesh
from src.models import BoundaryCondition, Load, StructuralAnalysisInput

_DOF_NUM = {"DX": 1, "DY": 2, "DZ": 3}


def _nodes_from_elset(mesh: dict, elset_name: str) -> list[int]:
    elset = mesh["elsets"].get(elset_name, [])
    node_ids: set[int] = set()
    for eid in elset:
        for nid in mesh["elements"].get(eid, []):
            node_ids.add(nid)
    return sorted(node_ids)


def _format_nset(name: str, node_ids: list[int]) -> list[str]:
    lines = [f"*NSET, NSET={name}"]
    chunk: list[str] = []
    for nid in node_ids:
        chunk.append(str(nid))
        if len(chunk) == 16:
            lines.append(", ".join(chunk))
            chunk = []
    if chunk:
        lines.append(", ".join(chunk))
    return lines


def generate_inp(
    params: StructuralAnalysisInput,
    load_pressures: list[Load],
    mesh_include_path: str,
    job_name: str = "job",
) -> str:
    mesh = parse_inp_mesh(Path(params.mesh_path))
    lines: list[str] = []

    lines.append(f"** CalculiX job {job_name} — generated by calculix-mcp-server")
    lines.append(f"*INCLUDE, INPUT={mesh_include_path}")
    lines.append("")

    lines.append("*MATERIAL, NAME=STEEL")
    lines.append("*ELASTIC")
    lines.append(f"{params.material.E}, {params.material.NU}")
    lines.append(f"*SOLID SECTION, ELSET={params.solid_elset}, MATERIAL=STEEL")
    lines.append("")

    lines.append("*BOUNDARY")
    for bc in params.boundary_conditions:
        nset = bc.group_name
        if nset not in mesh["nsets"]:
            if nset in mesh["elsets"]:
                gen_name = f"BC_{nset}"
                nodes = _nodes_from_elset(mesh, nset)
                lines.extend(_format_nset(gen_name, nodes))
                lines.append("")
                nset = gen_name
            else:
                raise ValueError(
                    f"Boundary group '{bc.group_name}' not found as NSET or ELSET in mesh"
                )
        dof_nums = sorted({_DOF_NUM[d] for d in bc.fixed_dofs})
        if not dof_nums:
            continue
        first, last = min(dof_nums), max(dof_nums)
        lines.append(f"{nset}, {first}, {last}, 0")

    lines.append("")
    if load_pressures:
        lines.append("*DLOAD")
        for ld in load_pressures:
            if ld.group_name not in mesh["elsets"]:
                raise ValueError(f"Load ELSET '{ld.group_name}' not found in mesh")
            lines.append(f"{ld.group_name}, P, {ld.magnitude}")

    lines.append("")
    lines.append("*STEP")
    lines.append("*STATIC")
    lines.append("*NODE FILE")
    lines.append("U")
    lines.append("*EL FILE")
    lines.append("S")
    lines.append("*END STEP")
    return "\n".join(lines) + "\n"
